// Command genprofiles compiles directory host defaults into broker's profile table.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"

	dirapi "github.com/indexdata/crosslink/directory/api"
	"gopkg.in/yaml.v3"
)

func main() {
	input := flag.String("input", "../directory/api.yaml", "directory OpenAPI schema")
	output := flag.String("output", "profiles/builtin_gen.go", "generated Go output")
	flag.Parse()
	if err := run(*input, *output); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(input, output string) error {
	data, err := os.ReadFile(input)
	if err != nil {
		return fmt.Errorf("read directory schema: %w", err)
	}
	generated, err := generate(data)
	if err != nil {
		return err
	}
	if err := os.WriteFile(output, generated, 0600); err != nil {
		return fmt.Errorf("write profile table: %w", err)
	}
	return nil
}

func generate(data []byte) ([]byte, error) {
	var schema struct {
		Profiles   map[string]map[string]any `yaml:"x-host-profiles"`
		Components struct {
			Schemas map[string]struct {
				Enum []string `yaml:"enum"`
			} `yaml:"schemas"`
		} `yaml:"components"`
	}
	if err := yaml.Unmarshal(data, &schema); err != nil {
		return nil, fmt.Errorf("decode directory schema: %w", err)
	}
	if len(schema.Profiles) == 0 {
		return nil, fmt.Errorf("directory schema: missing or empty x-host-profiles")
	}
	for _, name := range []string{"Generic", "Alma", "Sierra", "Koha", "FOLIO"} {
		if schema.Profiles[name] == nil {
			return nil, fmt.Errorf("host profile %s: missing definition", name)
		}
	}
	vendors := map[string]bool{}
	for _, name := range schema.Components.Schemas["HostLmsVendor"].Enum {
		vendors[name] = true
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by genprofiles from directory/api.yaml; DO NOT EDIT.\n\npackage profiles\n\n// Merge copies nested maps before applying directory overrides.\nvar builtins = map[string]builtinProfile{\n")
	for _, name := range keys(schema.Profiles) {
		if !vendors[name] {
			return nil, fmt.Errorf("host profile %s: not in HostLmsVendor enum", name)
		}
		raw := schema.Profiles[name]
		// JSON decoding accepts case variants; table generation uses exact keys.
		for _, section := range keys(raw) {
			if section != "lmsConfig" && section != "catalogConfig" {
				return nil, fmt.Errorf("host profile %s: invalid section %q; allowed sections are lmsConfig and catalogConfig", name, section)
			}
		}
		encoded, err := json.Marshal(raw)
		if err != nil {
			return nil, fmt.Errorf("host profile %s: %w", name, err)
		}
		var config struct {
			LMS     *dirapi.LmsConfig     `json:"lmsConfig"`
			Catalog *dirapi.CatalogConfig `json:"catalogConfig"`
		}
		decoder := json.NewDecoder(bytes.NewReader(encoded))
		decoder.DisallowUnknownFields()
		if err := decoder.Decode(&config); err != nil {
			return nil, fmt.Errorf("host profile %s: %w", name, err)
		}
		// Normalize values to the same JSON map types used by the resolver.
		var profile map[string]any
		if err := json.Unmarshal(encoded, &profile); err != nil {
			return nil, fmt.Errorf("host profile %s: %w", name, err)
		}
		lms, err := literal(profile["lmsConfig"])
		if err != nil {
			return nil, fmt.Errorf("host profile %s: %w", name, err)
		}
		catalog, err := literal(profile["catalogConfig"])
		if err != nil {
			return nil, fmt.Errorf("host profile %s: %w", name, err)
		}
		fmt.Fprintf(&out, "%q: {LMS: %s, Catalog: %s},\n", name, lms, catalog)
	}
	out.WriteString("}\n")
	return format.Source(out.Bytes())
}

func keys[V any](m map[string]V) []string {
	result := make([]string, 0, len(m))
	for key := range m {
		result = append(result, key)
	}
	sort.Strings(result)
	return result
}

func literal(value any) (string, error) {
	switch v := value.(type) {
	case nil:
		return "nil", nil
	case string:
		return strconv.Quote(v), nil
	case bool:
		return strconv.FormatBool(v), nil
	case float64:
		return "float64(" + strconv.FormatFloat(v, 'g', -1, 64) + ")", nil
	case []any:
		var out bytes.Buffer
		out.WriteString("[]any{")
		for _, item := range v {
			itemLiteral, err := literal(item)
			if err != nil {
				return "", err
			}
			out.WriteString(itemLiteral)
			out.WriteByte(',')
		}
		out.WriteByte('}')
		return out.String(), nil
	case map[string]any:
		var out bytes.Buffer
		out.WriteString("object{")
		for _, key := range keys(v) {
			itemLiteral, err := literal(v[key])
			if err != nil {
				return "", err
			}
			fmt.Fprintf(&out, "%q: %s,", key, itemLiteral)
		}
		out.WriteByte('}')
		return out.String(), nil
	default:
		return "", fmt.Errorf("unexpected JSON value %T", value)
	}
}
